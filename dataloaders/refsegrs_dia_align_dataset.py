import json
import os
import random

import cv2
import numpy as np
import torch

from model.llava import conversation as conversation_lib
from model.llava.constants import DEFAULT_IMAGE_TOKEN
from .base_dataset import BaseDataset
from .qa_template import SHORT_ANSWER_TEMPLATE, NEG_ANSWER_TEMPLATE


DIA_ALIGN_QUESTION_TEMPLATE = [
    DEFAULT_IMAGE_TOKEN + "\n" + "Please segment the target described as follows if it is present: {description}",
    DEFAULT_IMAGE_TOKEN + "\n" + "Find the region matching this remote-sensing description and provide its mask if present: {description}",
    DEFAULT_IMAGE_TOKEN + "\n" + "Check whether this described target exists in the image, and segment it if found: {description}",
    DEFAULT_IMAGE_TOKEN + "\n" + "Use the description to locate the corresponding image region. Segment it only if the evidence is present: {description}",
]


class RefSegRSDIAAlignDataset(BaseDataset):
    """DIA alignment view of RefSegRS.

    Expected files are generated by tools/build_refsegrs_dia_align.py:
      <base_image_dir>/RefSegRS_DIAAlign/alignment_train.jsonl
      <base_image_dir>/RefSegRS_DIAAlign/views/<split>/{focus,removed}/*.png

    Positive samples keep the original mask and answer with [SEG]. Negative
    samples return an empty mask and answer without [SEG], so the LM learns to
    deny missing evidence while mask losses are skipped naturally.
    """

    def __init__(
        self,
        base_image_dir,
        vision_tower,
        samples_per_epoch=500 * 8 * 2 * 10,
        image_size: int = 224,
        num_classes_per_sample: int = 1,
        split: str = "train",
        is_train: bool | None = None,
        align_root_name: str = "RefSegRS_DIAAlign",
    ):
        super().__init__(vision_tower, samples_per_epoch, image_size)
        self.base_image_dir = base_image_dir
        self.num_classes_per_sample = num_classes_per_sample
        self.split = split
        self.is_train = (split == "train") if is_train is None else is_train
        self.question_list = DIA_ALIGN_QUESTION_TEMPLATE
        self.answer_list = SHORT_ANSWER_TEMPLATE
        self.neg_answer_list = NEG_ANSWER_TEMPLATE

        self.root = os.path.join(base_image_dir, align_root_name)
        jsonl_path = os.path.join(self.root, f"alignment_{split}.jsonl")
        if not os.path.exists(jsonl_path):
            raise FileNotFoundError(
                f"DIA alignment JSONL not found: {jsonl_path}. "
                "Run tools/build_refsegrs_dia_align.py first."
            )

        self.samples = []
        with open(jsonl_path, "r", encoding="utf-8") as handle:
            for line_no, line in enumerate(handle, start=1):
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                image_path = self._resolve_path(record["image_path"])
                mask_path = self._resolve_path(record["mask_path"])
                if os.path.exists(image_path) and os.path.exists(mask_path):
                    record["_jsonl_line_no"] = line_no
                    self.samples.append(record)

        if not self.samples:
            raise RuntimeError(f"No usable RefSegRS_DIAAlign samples found in {jsonl_path}")
        mode = "train" if self.is_train else "eval"
        print(f"RefSegRS_DIAAlign({split}, {mode}) has {len(self.samples)} usable records.")

    def _resolve_path(self, path):
        if os.path.isabs(path):
            return path
        return os.path.join(self.base_image_dir, path)

    def __len__(self):
        if self.is_train:
            return self.samples_per_epoch
        if self.samples_per_epoch and self.samples_per_epoch > 0:
            return min(int(self.samples_per_epoch), len(self.samples))
        return len(self.samples)

    def _load_mask(self, mask_path):
        mask = cv2.imread(mask_path, cv2.IMREAD_UNCHANGED)
        if mask is None:
            raise FileNotFoundError(mask_path)
        if mask.ndim == 3:
            mask = mask[..., 0]
        return (mask > 0).astype(np.float32)

    def __getitem__(self, idx):
        if self.is_train:
            record = random.choice(self.samples)
        else:
            record = self.samples[idx % len(self.samples)]

        image_path = self._resolve_path(record["image_path"])
        mask_path = self._resolve_path(record["mask_path"])
        image, image_clip, sam_input_shape = self.load_and_preprocess_image(image_path)
        mask = self._load_mask(mask_path)
        is_positive = bool(record.get("is_positive", False))

        if is_positive:
            masks = torch.from_numpy(mask[None, ...])
            exists = [True]
            answer_template = random.choice(self.answer_list)
        else:
            masks = torch.zeros((0, *mask.shape), dtype=torch.float32)
            exists = [False]
            answer_template = random.choice(self.neg_answer_list)

        description = record.get("detailed_text") or record.get("phrase", "target")
        phrase = record.get("phrase", "target")
        question = random.choice(self.question_list).format(description=description)
        answer = answer_template.format(class_name=phrase)

        conv = conversation_lib.default_conversation.copy()
        conv.append_message(conv.roles[0], question)
        conv.append_message(conv.roles[1], answer)

        sam_mask_shape = [sam_input_shape, (int(mask.shape[0]), int(mask.shape[1]))]
        sample_id = f"{record.get('image_id', 'unknown')}_{record.get('_jsonl_line_no', idx)}"
        return (
            image_path,
            image,
            image_clip,
            [conv.get_prompt()],
            masks,
            sam_mask_shape,
            exists,
            [sample_id],
            [record.get("line_no", record.get("_jsonl_line_no", idx))],
        )
